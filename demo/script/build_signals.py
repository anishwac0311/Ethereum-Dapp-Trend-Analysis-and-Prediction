"""Build site/js/signals.js: every early signal's weight in each era's model, ranked.

Source: data/coef_by_period.csv, copied from the time-split-analysis branch
(model/dapp_timesplit/results/tables/coef_by_period.csv): 27 features x 3 eras, the logistic
coefficients of each era's model with 1,000-resample intervals.

share  = |coef| / sum of |coef| in that era (the same measure as the group weights)

Run from demo/:  python3 script/build_signals.py
"""
import csv, json
from pathlib import Path

HOME = Path(__file__).resolve().parents[1]
ERA = {"Before Terra": "before", "Terra to Dencun": "between", "After Dencun": "after"}

rows = list(csv.DictReader(open(HOME / "data" / "coef_by_period.csv")))
out = {}
for name, key in ERA.items():
    rr = sorted((r for r in rows if r["period"] == name), key=lambda r: -abs(float(r["coef"])))
    total = sum(abs(float(r["coef"])) for r in rr)
    cum, sig = 0.0, []
    for i, r in enumerate(rr, 1):
        c = float(r["coef"]); share = abs(c) / total; cum += share
        sig.append({"rank": i, "feature": r["feature"], "group": r["group"], "coef": round(c, 3),
                    "share": round(share, 4), "cum": round(cum, 4)})
    out[key] = sig

js = ("/* Generated by script/build_signals.py from data/coef_by_period.csv. Do not edit by hand. */\n"
      "window.SIGNALS = " + json.dumps(out, separators=(",", ":")) + ";\n")
(HOME / "site" / "js" / "signals.js").write_text(js)
print({k: [(s["feature"], round(s["share"] * 100, 1)) for s in v[:5]] for k, v in out.items()})
